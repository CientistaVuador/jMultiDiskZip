    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        JFileChooser chooser = new JFileChooser();
        chooser.setFileSelectionMode(JFileChooser.FILES_AND_DIRECTORIES);
        chooser.setMultiSelectionEnabled(true);
        int result = chooser.showOpenDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            File[] files = chooser.getSelectedFiles();
            DefaultListModel<String> model = (DefaultListModel<String>) this.fileList.getModel();
            for (int i = 0; i < files.length; i++) {
                String element = files[i].toString();
                if (!model.contains(element)) {
                    model.addElement(element);
                }
            }
        }
    }//GEN-LAST:event_addButtonActionPerformed

    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        int[] selected = this.fileList.getSelectedIndices();
        String[] toRemove = new String[selected.length];
        for (int i = 0; i < selected.length; i++) {
            toRemove[i] = this.fileList.getModel().getElementAt(selected[i]);
        }
        for (String s : toRemove) {
            ((DefaultListModel<String>) this.fileList.getModel()).removeElement(s);
        }
    }//GEN-LAST:event_removeButtonActionPerformed

