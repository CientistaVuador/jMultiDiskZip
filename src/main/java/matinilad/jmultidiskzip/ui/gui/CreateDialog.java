    private void outputFileButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_outputFileButtonActionPerformed
        JFileChooser chooser = new JFileChooser();
        if (this.fileList.getModel().getSize() != 0) {
            File file = new File(this.fileList.getModel().getElementAt(0));
            if (file.getParentFile() != null) {
                chooser.setCurrentDirectory(file.getParentFile());
            } else {
                chooser.setCurrentDirectory(file);
            }
        }
        chooser.setFileSelectionMode(JFileChooser.FILES_ONLY);
        int result = chooser.showSaveDialog(this);
        if (result == JFileChooser.APPROVE_OPTION) {
            this.outputFileField.setText(chooser.getSelectedFile().toString());
            this.createButton.setEnabled(true);
        }
    }//GEN-LAST:event_outputFileButtonActionPerformed

    private void createButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_createButtonActionPerformed
        byte[] salt = null;
        char[] password = null;
        if (this.encryptWithAPassword.isSelected()) {
            salt = this.randomCharacters.getText().getBytes(StandardCharsets.UTF_8);
            password = this.passwordField.getPassword();
            if (password.length == 0) {
                Toolkit.getDefaultToolkit().beep();
                JOptionPane.showMessageDialog(this, "Password is empty", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        }

        CreateOperation operation;
        try {
            this.passwordField.setText("");
            DefaultListModel<String> model = (DefaultListModel<String>) this.fileList.getModel();

            Path outputFile = Path.of(this.outputFileField.getText());
            Path[] inputFiles = new Path[model.size()];
            for (int i = 0; i < inputFiles.length; i++) {
                inputFiles[i] = Path.of(model.elementAt(i));
            }

            CreateOperationSettings settings = new CreateOperationSettings();
            settings.load();
            CreateOperationData data = new CreateOperationData(settings, outputFile, inputFiles, salt, password);
            try {
                if (getParent() instanceof Dialog d) {
                    operation = new CreateOperation(data, d, true);
                } else if (getParent() instanceof Frame f) {
                    operation = new CreateOperation(data, f, true);
                } else {
                    operation = new CreateOperation(data, (Frame) null, true);
                }
            } finally {
                data.clearPassword();
            }
        } finally {
            if (password != null) {
                Arrays.fill(password, '\0');
            }
        }

        setVisible(false);
        dispose();

        if (this.auto) {
            operation.setCloseAfterFinishEnabled(true);
        }
        operation.start();
        operation.setVisible(true);
    }//GEN-LAST:event_createButtonActionPerformed

